"""Build the reopen-watch table of Monday-open gaps.

Usage: python3 scripts/gaps.py WEEKENDS_CSV ARCUS_MARKETS_JSON OUT...

Reads Weekend Oracle's weekends.csv and Arcus's /v1/markets, counts per market how many weekends opened at least
N% away from the Friday close, and writes the table to each OUT: a JavaScript module for the site, or a typed
module for the agent when OUT ends in .ts.
"""

import csv
import json
import sys

# An index or a future stands in for the ETF that Arcus lists.
ALIAS = {'^GSPC': 'SPY', '^NDX': 'QQQ', 'GC=F': 'GLD', 'SI=F': 'SLV', 'CL=F': 'USO'}
CATEGORIES = ('EQUITIES', 'INDICES', 'COMMODITIES')
STEPS = [round(0.5 * i, 1) for i in range(1, 31)]  # 0.5% to 15%
GAPS_TYPE = ': Record<string, { n: number; down: number[]; up: number[] }>'


def table(gaps):
    return {
        'n': len(gaps),
        'down': [sum(g <= -t for g in gaps) for t in STEPS],
        'up': [sum(g >= t for g in gaps) for t in STEPS],
    }


def header(first, last):
    return (
        '// Monday-open gaps against the Friday close, one reading per market per weekend: how many weekends opened at least N% lower\n'
        '// (down) or higher (up), N = GAP_META.steps. US = every US share in the set. SPY and QQQ use the S&P 500 and Nasdaq-100,\n'
        f"// GLD/SLV/USO the gold, silver and crude futures. Source: Weekend Oracle's weekends.csv, {first} to {last}.\n"
        '// Generated by scripts/gaps.py (see ARCHITECTURE.md); do not edit by hand.\n'
    )


def main(weekends_csv, arcus_json, *outs):
    # The CSV can list a market twice in one weekend; the first reading counts.
    readings = {}
    with open(weekends_csv) as f:
        for row in csv.DictReader(f):
            if row['actual'] in ('', 'nan'):
                continue
            key = (row['weekend'], ALIAS.get(row['symbol'], row['symbol']))
            readings.setdefault(key, (row['group'], float(row['actual']) * 100))
    with open(arcus_json) as f:
        listed = {m['baseAsset'] for m in json.load(f)['markets'] if m.get('category') in CATEGORIES}

    weeks = sorted({week for week, _ in readings})
    meta = {'from': weeks[0], 'to': weeks[-1], 'weekends': len(weeks), 'steps': STEPS}
    out = {'US': table([gap for group, gap in readings.values() if group == 'us_shares'])}
    for symbol in sorted({s for _, s in readings} & listed):
        out[symbol] = table([gap for (_, s), (_, gap) in readings.items() if s == symbol])

    head = header(weeks[0], weeks[-1])
    for path in outs:
        typed = GAPS_TYPE if path.endswith('.ts') else ''
        body = (
            f"export const GAP_META = {json.dumps(meta, separators=(',', ':'))};\n"
            f"export const GAPS{typed} = {json.dumps(out, separators=(',', ':'))};\n"
        )
        with open(path, 'w') as f:
            f.write(head + body)

    us = out['US']
    i2, i5 = STEPS.index(2.0), STEPS.index(5.0)
    at2 = (us['down'][i2] + us['up'][i2]) / us['n']
    at5 = (us['down'][i5] + us['up'][i5]) / us['n']
    print(f"weekends {len(weeks)}, markets {len(out) - 1}, US share-weekends {us['n']}: >=2% {at2:.1%}, >=5% {at5:.1%}")
    for s in ('SPY', 'QQQ', 'NVDA', 'TSLA', 'HOOD', 'GLD'):
        if s in out:
            t = out[s]
            print(
                f"  {s:5} n {t['n']:3}  down>=2% {t['down'][i2]:2}  down>=5% {t['down'][i5]:2}"
                f"  up>=2% {t['up'][i2]:2}  up>=5% {t['up'][i5]:2}"
            )
    print('wrote', ', '.join(outs))


if __name__ == '__main__':
    main(*sys.argv[1:])
